/**
 * Inline each language's runtime support files into TypeScript modules.
 *
 * The browser build has no filesystem, so it cannot read a support file off
 * disk the way the desktop runtimes do. Rather than couple the packages to a
 * bundler feature (Vite's `?raw`), the sources are embedded into checked-in
 * modules by this script, and a test asserts they have not drifted.
 *
 * Run with: node scripts/generate-python-sources.mjs [--check]
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** @type {{ output: string, banner: string, files: { constant: string, source: string }[] }[]} */
const targets = [
  {
    output: 'languages/python/src/support-sources.generated.ts',
    banner: [
      'The Python support modules, inlined as strings.',
      '',
      'The desktop runtime puts these files on PYTHONPATH from disk; the browser',
      'runtime writes them into the WASM filesystem from here. Same bytes, so an',
      'exercise cannot behave differently depending on where it runs.',
    ].join('\n'),
    files: [
      { constant: 'INIT_PY', source: 'languages/python/runtime/retrainer/__init__.py' },
      { constant: 'REPORT_PY', source: 'languages/python/runtime/retrainer/report.py' },
      { constant: 'EXPECT_PY', source: 'languages/python/runtime/retrainer/expect.py' },
      { constant: 'TRACE_PY', source: 'languages/python/runtime/retrainer/trace.py' },
    ],
  },
  {
    output: 'languages/javascript/src/support-sources.generated.ts',
    banner: [
      'The JavaScript support package, inlined as strings.',
      '',
      'The desktop runtime copies these files into a sandbox from disk; the',
      'browser runtime turns them into blob modules from here. Same bytes, so a',
      'test cannot behave differently depending on where it runs.',
    ].join('\n'),
    files: [
      { constant: 'TEST_JS', source: 'languages/javascript/runtime/retrainer/test.js' },
      { constant: 'EXPECT_JS', source: 'languages/javascript/runtime/retrainer/expect.js' },
      { constant: 'RUN_JS', source: 'languages/javascript/runtime/retrainer/run.js' },
    ],
  },
  {
    output: 'packages/runtime-web/src/python-sources.generated.ts',
    banner: 'The in-WASM host helpers, inlined as a string.',
    files: [{ constant: 'PYODIDE_HOST_PY', source: 'packages/runtime-web/python/pyodide_host.py' }],
  },
  {
    output: 'apps/web/src/platform/sql-sources.generated.ts',
    banner: [
      'The SQL harness, inlined for the browser.',
      '',
      'These are the same two files the desktop runtime hands to a real Python',
      'process. The browser writes them into the interpreter it already has, so',
      'a query graded in a tab is graded by the identical code that grades it on',
      'the desktop -- not by a second implementation that agrees until it does not.',
    ].join('\n'),
    files: [
      { constant: 'SQL_HARNESS_PY', source: 'languages/sql/runtime/harness.py' },
      { constant: 'SQL_RUN_PY', source: 'languages/sql/runtime/run.py' },
    ],
  },
];

/** Embed as a JSON string literal: no escaping surprises, no template-literal traps. */
function literal(contents) {
  return JSON.stringify(contents);
}

async function render(target) {
  const parts = [
    '// Copyright 2026 Ryan P. Walsh (rpwalsh.github.io)',
    '// @generated by scripts/generate-python-sources.mjs — do not edit by hand.',
    '// Edit the .py files and re-run the script.',
    '',
    '/**',
    ...target.banner.split('\n').map((line) => (line ? ` * ${line}` : ' *')),
    ' */',
    '',
  ];

  for (const file of target.files) {
    const contents = await readFile(path.join(root, file.source), 'utf8');
    parts.push(`/** Source: \`${file.source}\` */`);
    parts.push(`export const ${file.constant}: string = ${literal(contents)};`);
    parts.push('');
  }

  return parts.join('\n');
}

const check = process.argv.includes('--check');
let drifted = false;

for (const target of targets) {
  const rendered = await render(target);
  const outputPath = path.join(root, target.output);

  let existing = null;
  try {
    existing = await readFile(outputPath, 'utf8');
  } catch {
    existing = null;
  }

  if (existing === rendered) continue;

  if (check) {
    drifted = true;
    console.error(`${target.output} is out of date.`);
    continue;
  }

  await writeFile(outputPath, rendered, 'utf8');
  console.log(`wrote ${target.output}`);
}

if (check && drifted) {
  console.error('\nRun: node scripts/generate-python-sources.mjs');
  process.exitCode = 1;
} else if (check) {
  console.log('Generated Python sources are up to date.');
}
